def create_database():
    """Створює SQLite базу даних та заповнює питаннями."""
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)

    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    cur.executescript('''
        CREATE TABLE questions (
            id       INTEGER PRIMARY KEY AUTOINCREMENT,
            topic    TEXT    NOT NULL,
            question TEXT    NOT NULL,
            type     TEXT    NOT NULL CHECK(type IN ('single','multiple'))
        );
        CREATE TABLE answers (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            question_id INTEGER NOT NULL,
            answer_text TEXT    NOT NULL,
            is_correct  INTEGER NOT NULL DEFAULT 0,
            FOREIGN KEY (question_id) REFERENCES questions(id)
        );
    ''')

    for q in QUESTIONS:
        cur.execute(
            "INSERT INTO questions (topic, question, type) VALUES (?,?,?)",
            (q["topic"], q["question"], q["type"])
        )
        q_id = cur.lastrowid
        for text, correct in q["answers"]:
            cur.execute(
                "INSERT INTO answers (question_id, answer_text, is_correct) VALUES (?,?,?)",
                (q_id, text, 1 if correct else 0)
            )

    conn.commit()
    total_q = cur.execute("SELECT COUNT(*) FROM questions").fetchone()[0]
    total_a = cur.execute("SELECT COUNT(*) FROM answers").fetchone()[0]
    conn.close()

    print(f"✓ База даних створена: {DB_PATH}")
    print(f"  Питань: {total_q}")
    print(f"  Варіантів відповідей: {total_a}")


def export_json():
    """Повертає JSON з усіма питаннями для вбудовування в HTML."""
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    rows = cur.execute("SELECT * FROM questions ORDER BY id").fetchall()
    result = []
    for q in rows:
        answers = cur.execute(
            "SELECT id, answer_text, is_correct FROM answers WHERE question_id=? ORDER BY id",
            (q["id"],)
        ).fetchall()
        result.append({
            "id": q["id"],
            "topic": q["topic"],
            "question": q["question"],
            "type": q["type"],
            "answers": [
                {"id": a["id"], "text": a["answer_text"], "correct": bool(a["is_correct"])}
                for a in answers
            ]
        })
    conn.close()
    return result


